/**
 * Static export for a Netlify drag-and-drop deploy.
 *
 * A normal `next build` produces a SERVER build in `.next/` that includes
 * Payload (/admin, /api, mongoose) and cannot be dropped on Netlify as static
 * files. Payload is also incompatible with Next's `output: 'export'`.
 *
 * Moving `(payload)` out of the live project fails on Windows (EPERM) whenever
 * the IDE or `next dev` holds a file handle inside it. So this script never
 * touches your project. Instead it:
 *   1. Mirrors the project into a sibling build folder (excluding node_modules,
 *      .next, .git, out, out-netlify) with robocopy.
 *   2. Mirrors node_modules into it separately (first run slow, then incremental).
 *   3. Deletes `(payload)` from the COPY (not locked) and writes an export config.
 *   4. Runs `next build` in the copy -> static site in <copy>/out.
 *   5. Mirrors that into this project's out-netlify/.
 *
 * Your real project is read-only here; nothing in it is moved or modified.
 *
 * Run it yourself:   npm run build:netlify
 * Windows only (uses robocopy). Leaving the IDE / dev server open is fine.
 */

import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, basename } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
// Sibling folder (outside the project so the IDE doesn't index it).
const BUILD_DIR = join(ROOT, '..', `${basename(ROOT)}-netlify-build`)

const EXPORT_CONFIG = `/** Generated by scripts/build-netlify.mjs for the static Netlify export. */
const nextConfig = {
  output: 'export',
  images: { unoptimized: true },
  eslint: { ignoreDuringBuilds: true },
}
export default nextConfig
`

function log(step) {
  console.log(`\n→ ${step}`)
}

// robocopy returns 0-7 on success (files copied / nothing to do) and >=8 on
// real failure, so we can't treat any non-zero exit as an error.
function robocopy(src, dst, extraArgs = []) {
  try {
    execFileSync(
      'robocopy',
      [src, dst, ...extraArgs, '/NFL', '/NDL', '/NJH', '/NJS', '/NP', '/R:1', '/W:1'],
      { stdio: 'ignore' },
    )
  } catch (err) {
    const code = typeof err.status === 'number' ? err.status : 16
    if (code >= 8) {
      throw new Error(`robocopy failed (exit ${code}) copying ${src} -> ${dst}`)
    }
  }
}

if (process.platform !== 'win32') {
  console.error('This script uses robocopy and is Windows-only.')
  process.exit(1)
}

try {
  mkdirSync(dirname(BUILD_DIR), { recursive: true })

  // 1. Mirror the source tree (minus the heavy / generated dirs). /MIR keeps the
  //    copy in sync on repeat runs, deleting stale files but leaving the excluded
  //    dirs (node_modules, out) in the copy untouched.
  log('Syncing source into build copy')
  robocopy(ROOT, BUILD_DIR, [
    '/MIR',
    '/XD',
    join(ROOT, 'node_modules'),
    join(ROOT, '.next'),
    join(ROOT, '.git'),
    join(ROOT, 'out'),
    join(ROOT, 'out-netlify'),
    join(ROOT, '.idea'),
    BUILD_DIR,
  ])

  // 2. Mirror node_modules (first run is slow; later runs only copy changes).
  log('Syncing node_modules (first run is slow)')
  robocopy(join(ROOT, 'node_modules'), join(BUILD_DIR, 'node_modules'), ['/MIR'])

  // 3. In the COPY: drop the Payload route group and use a plain export config.
  log('Removing (payload) from the copy and writing export config')
  rmSync(join(BUILD_DIR, 'src', 'app', '(payload)'), { recursive: true, force: true })
  writeFileSync(join(BUILD_DIR, 'next.config.mjs'), EXPORT_CONFIG)
  rmSync(join(BUILD_DIR, '.next'), { recursive: true, force: true })
  rmSync(join(BUILD_DIR, 'out'), { recursive: true, force: true })

  // 4. Build the static site inside the copy.
  log('Building static export (next build)')
  const nextBin = join(BUILD_DIR, 'node_modules', 'next', 'dist', 'bin', 'next')
  execFileSync('node', [nextBin, 'build'], {
    cwd: BUILD_DIR,
    stdio: 'inherit',
    env: { ...process.env, NEXT_TELEMETRY_DISABLED: '1' },
  })

  const builtOut = join(BUILD_DIR, 'out')
  if (!existsSync(builtOut)) {
    throw new Error('Build finished but no out/ folder was produced in the copy.')
  }

  // 5. Mirror the result into this project's out-netlify/.
  log('Updating out-netlify/')
  robocopy(builtOut, join(ROOT, 'out-netlify'), ['/MIR'])

  console.log('\n✓ Done. Drag the out-netlify/ folder onto Netlify.')
  console.log(`  (Build copy kept at ${BUILD_DIR} so the next run is fast.)`)
} catch (err) {
  console.error('\n✗ Build failed:', err.message)
  process.exit(1)
}
